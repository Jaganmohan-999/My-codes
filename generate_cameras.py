    parsed = urlparse(rtsp_url)

    username = unquote(parsed.username) if parsed.username else ""
    password = unquote(parsed.password) if parsed.password else ""

    return {
        "username": username,
        "password": password,
        "ipAddress": parsed.hostname,
        "port": parsed.port,
        "path": parsed.path
    }

